function table(cols, rows, o = {}) {
  const total = cols.reduce((a, b) => a + b, 0);
  const mk = (cells, head) => new TableRow({ tableHeader: head, cantSplit: true, children: cells.map((c, i) => new TableCell({
    width: { size: cols[i], type: WidthType.DXA }, borders,
    shading: head ? { type: ShadingType.CLEAR, color: 'auto', fill: HEAD_BG } : undefined,
    margins: { top: 70, bottom: 70, left: 110, right: 110 },
    children: (Array.isArray(c) ? c : [c]).map(x => typeof x === 'string'
      ? new Paragraph({ children: [r(x, { bold: head || (o.boldFirst && i === 0), size: 19 })], spacing: { after: 40, line: 260 } })
      : x)
  })) });
  return new Table({ width: { size: total, type: WidthType.DXA }, columnWidths: cols, rows: [mk(o.head, true), ...rows.map(x => mk(x, false))] });
}
